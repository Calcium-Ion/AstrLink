#!/bin/sh
# Copies new-api's official plugins and the top-level meta fields of its
# plugin API v1 schema into Core's conformance testdata, and writes the keys
# new-api refuses as its own paths into core/internal/plugin. Needs Go.
#
#   scripts/refresh-newapi-conformance.sh <new-api checkout>
set -eu

if [ "$#" -ne 1 ] || [ ! -f "$1/docs/plugin-api/v1.schema.json" ] || [ ! -d "$1/plugins/tasks" ]; then
	echo "usage: $0 <new-api checkout>" >&2
	exit 2
fi
source_dir=$1
target=$(cd "$(dirname "$0")/.." && pwd)/core/internal/plugin/testdata/newapi-conformance

commit=$(git -C "$source_dir" rev-parse HEAD)
rm -rf "$target/plugins"
mkdir -p "$target/plugins"
for dir in "$source_dir"/plugins/tasks/*/; do
	key=$(basename "$dir")
	[ -f "$dir/plugin.js" ] || continue
	mkdir -p "$target/plugins/$key"
	cp "$dir/plugin.js" "$target/plugins/$key/plugin.js"
done
python3 - "$source_dir/docs/plugin-api/v1.schema.json" "$target/meta-fields.json" <<'PY'
import json, sys
with open(sys.argv[1]) as schema:
    fields = sorted(json.load(schema)["properties"])
with open(sys.argv[2], "w") as out:
    json.dump(fields, out, indent=2)
    out.write("\n")
PY
# The keys new-api refuses as its own paths, for astrlink plugin new and
# check. The lister runs in a module that points at the checkout.
lister=$(mktemp -d)
trap 'rm -rf "$lister"' EXIT
cp "$(dirname "$0")/newapi-reserved-keys/main.go" "$lister/main.go"
go_version=$(sed -n 's/^go //p' "$source_dir/go.mod")
cat > "$lister/go.mod" <<MOD
module newapireservedkeys

go $go_version

require github.com/QuantumNous/new-api v0.0.0

replace github.com/QuantumNous/new-api => $(cd "$source_dir" && pwd)
MOD
sed -n 's#^replace \(github.com/QuantumNous/new-api/[a-z]*\) => \./\(.*\)$#replace \1 => '"$(cd "$source_dir" && pwd)"'/\2#p' "$source_dir/go.mod" >> "$lister/go.mod"
cp "$source_dir/go.sum" "$lister/go.sum"
(cd "$lister" && GOTOOLCHAIN=auto go mod tidy >/dev/null && GOTOOLCHAIN=auto go run . "$(cd "$source_dir" && pwd)") > "$lister/keys.json"
python3 - "$lister/keys.json" "$commit" "$(dirname "$0")/../core/internal/plugin/newapi_reserved_keys.go" <<'PY'
import json, sys
keys = json.load(open(sys.argv[1]))
assert "api" in keys and "v1" in keys, keys
lines = "".join('\t"%s",\n' % key for key in keys)
with open(sys.argv[3], "w") as out:
    out.write("""// Code generated by scripts/refresh-newapi-conformance.sh from new-api
// commit %s. DO NOT EDIT.

package plugin

// newAPIReservedKeys are the plugin keys new-api refuses as its own paths:
// api, the first segments of its routes, and the prefixes its built-in
// plugins own.
var newAPIReservedKeys = []string{
%s}
""" % (sys.argv[2], lines))
PY
gofmt -w "$(dirname "$0")/../core/internal/plugin/newapi_reserved_keys.go"

cat > "$target/SOURCE" <<TXT
Copied from https://github.com/QuantumNous/new-api at commit $commit:
plugins/tasks/*/plugin.js into plugins/, and the top-level property names
of docs/plugin-api/v1.schema.json into meta-fields.json. new-api is
licensed under AGPL-3.0 (LICENSES/AGPL-3.0.txt). Refresh with
scripts/refresh-newapi-conformance.sh <new-api checkout>.
TXT
echo "copied $(ls "$target/plugins" | wc -l | tr -d ' ') plugins from $commit"
