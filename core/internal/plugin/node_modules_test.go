// nodeFixture is a directory plugin on disk with its own data directory.
type nodeFixture struct {
	plugin  *Plugin
	install string
	data    string
}

// newNodeFixture installs an apiVersion 2 plugin of body, with files beside
// it in its install directory, and loads it with services.
func newNodeFixture(t *testing.T, body string, files map[string]string, services Services, limits Limits, capabilities ...string) nodeFixture {
	t.Helper()
	root, err := filepath.EvalSymlinks(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	install := filepath.Join(root, "plugins", "demo")
	if err := os.MkdirAll(install, 0o755); err != nil {
		t.Fatal(err)
	}
	files["plugin.js"] = pluginSourceV2("demo", capabilities, body)
	for name, text := range files {
		if err := os.MkdirAll(filepath.Dir(filepath.Join(install, name)), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(filepath.Join(install, name), []byte(text), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	manager := NewManager(ManagerOptions{
		Dir:      filepath.Join(root, "plugins"),
		DataDir:  filepath.Join(root, "plugin-data"),
		Settings: settingsMap{"demo": enabled(capabilities...)},
		Services: services,
		Limits:   limits,
	})
	if err := manager.Reload(context.Background()); err != nil {
		t.Fatal(err)
	}
	return nodeFixture{plugin: loadedPlugin(t, manager, "demo"), install: install, data: filepath.Join(root, "plugin-data", "demo")}
}

// call runs prepareTurn and decodes its result into target.
func (fixture nodeFixture) call(t *testing.T, target any) CallInfo {
	t.Helper()
	outcome := callWithin(t, context.Background(), fixture.plugin, HookPrepareTurn, nil, CallOptions{NetworkBudget: 5 * time.Second})
	if outcome.err != nil {
		t.Fatalf("call: %v", outcome.err)
	}
	if err := json.Unmarshal(outcome.result, target); err != nil {
		t.Fatalf("result %s: %v", outcome.result, err)
	}
	return outcome.info
}

