import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import {
  mkdirSync,
  readFileSync,
  renameSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";

export const windowsVcRuntime = JSON.parse(
  readFileSync(new URL("./windows-vc-runtime.json", import.meta.url), "utf8"),
);

export function verifyWindowsVcRuntime(bytes, asset = windowsVcRuntime) {
  if (
    bytes.byteLength !== asset.size ||
    createHash("sha256").update(bytes).digest("hex") !== asset.sha256
  ) {
    throw new Error(
      "Pinned Visual C++ x64 Redistributable failed integrity verification.",
    );
  }
}

export async function stageWindowsVcRuntime({
  target,
  binariesDirectory,
  fetchAsset = fetch,
  asset = windowsVcRuntime,
}) {
  if (!target.includes("windows")) return;
  if (target !== "x86_64-pc-windows-msvc") {
    throw new Error(
      `Unsupported Windows target for bundled Visual C++ runtime: ${target}`,
    );
  }

  mkdirSync(binariesDirectory, { recursive: true });
  const destination = path.join(binariesDirectory, "vc_redist.x64.exe");
  let cached = false;
  try {
    verifyWindowsVcRuntime(readFileSync(destination), asset);
    cached = true;
  } catch {
    rmSync(destination, { force: true });
  }
  if (!cached) {
    const response = await fetchAsset(asset.url, { redirect: "follow" });
    if (!response.ok) {
      throw new Error(
        `Unable to download Visual C++ runtime: HTTP ${response.status}`,
      );
    }
    const bytes = Buffer.from(await response.arrayBuffer());
    verifyWindowsVcRuntime(bytes, asset);
    const temporary = `${destination}.${process.pid}.download`;
    try {
      writeFileSync(temporary, bytes, { mode: 0o600 });
      renameSync(temporary, destination);
    } finally {
      rmSync(temporary, { force: true });
    }
  }

  // In addition to the pinned hash, validate Microsoft's signature on the build host.
  // Pass the path through the environment so it is never interpolated into PowerShell.
  if (process.platform === "win32") {
    // Bun inherits PowerShell 7 module paths that Windows PowerShell cannot load.
    const env = Object.fromEntries(
      Object.entries(process.env).filter(
        ([key]) => key.toUpperCase() !== "PSMODULEPATH",
      ),
    );
    execFileSync(
      "powershell.exe",
      [
        "-NoProfile",
        "-NonInteractive",
        "-Command",
        "$ErrorActionPreference = 'Stop'; " +
          "$signature = Get-AuthenticodeSignature -LiteralPath $env:ASTRLINK_VC_REDIST_FILE; " +
          "if ($signature.Status -ne 'Valid' -or " +
          "$signature.SignerCertificate.Subject -notmatch '(^|,\\s*)O=Microsoft Corporation(,|$)') " +
          "{ throw 'Visual C++ Redistributable must have a valid Microsoft signature' }",
      ],
      {
        stdio: "inherit",
        env: { ...env, ASTRLINK_VC_REDIST_FILE: destination },
      },
    );
  }

  writeFileSync(
    path.join(binariesDirectory, "vc_redist.x64.nsh"),
    `; Generated by stage-windows-vc-runtime.mjs; do not edit.\n` +
      `!define ASTRLINK_VC_RUNTIME_VERSION "${asset.version}"\n`,
  );
  console.log(`Staged Microsoft Visual C++ x64 runtime ${asset.version}.`);
}
